#1.4循环嵌套
#示例：
# while 条件1：
#     条件1满足时做的事情1
#     条件1满足时做的事情2
#     ......
#     while 条件2：
#         条件2满足时做的事情1
#         条件2满足时做的事情2
#         ......
i=1
while i<=3:
    print(f'这是第{i}次外循环')
    j = 1
    while j<=5:
        print(f'内循环{j}次')
        j+=1
    i+=1