# 修改元素
# 变量名[键名] = 值
dic = {'name':'bingbing','age':18}
dic['age']= 20  # 列表通过下标修改，字典通过键名修改
print(dic)
# 如果键名不存在，会新增元素:
dic['tel'] = 15674867531
print(dic)


